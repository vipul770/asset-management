from fastapi import APIRouter, Depends, HTTPException
from sqlalchemy.orm import Session
from typing import List
from app.database import get_db
from app.models.report import Report
from app.models.asset import Asset
from app.models.maintenance import MaintenanceRequest
from app.models.user import User as UserModel
from app.schemas.report import ReportCreate, ReportResponse
from app.utils.deps import get_current_user
from app.models.user import User

router = APIRouter(prefix="/api/reports", tags=["Reports"])


@router.get("", response_model=List[ReportResponse])
def get_all_reports(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    return db.query(Report).order_by(Report.created_at.desc()).all()


@router.post("", response_model=ReportResponse, status_code=201)
def create_report(
    data: ReportCreate,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    count     = db.query(Report).count()
    report_id = f"RPT-{count + 1:03d}"
    report = Report(
        **data.model_dump(),
        report_id       = report_id,
        status          = 'ready',
        generated_by_id = current_user.id
    )
    db.add(report)
    db.commit()
    db.refresh(report)
    return report


@router.get("/dashboard-stats")
def get_dashboard_stats(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    return {
        "total_assets":        db.query(Asset).count(),
        "assigned_assets":     db.query(Asset).filter(Asset.status == 'assigned').count(),
        "available_assets":    db.query(Asset).filter(Asset.status == 'available').count(),
        "maintenance_assets":  db.query(Asset).filter(Asset.status == 'maintenance').count(),
        "total_users":         db.query(UserModel).count(),
        "active_users":        db.query(UserModel).filter(UserModel.is_active == True).count(),
        "pending_maintenance": db.query(MaintenanceRequest).filter(MaintenanceRequest.status == 'pending').count(),
        "total_reports":       db.query(Report).count(),
    }


@router.get("/recent-activity")
def get_recent_activity(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    from datetime import datetime, timezone

    def time_ago(dt):
        if not dt:
            return "just now"
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        now  = datetime.now(timezone.utc)
        diff = int((now - dt).total_seconds())
        if diff < 60:    return f"{diff}s ago"
        if diff < 3600:  return f"{diff // 60} mins ago"
        if diff < 86400: return f"{diff // 3600} hours ago"
        return               f"{diff // 86400} days ago"

    activities = []
    is_admin_or_manager = current_user.role.lower() in ['admin', 'manager']

    # Assets — admin/manager see all, employee sees only their assigned
    if is_admin_or_manager:
        recent_assets = db.query(Asset).order_by(Asset.created_at.desc()).limit(3).all()
    else:
        recent_assets = (
            db.query(Asset)
            .filter(Asset.assigned_to_id == current_user.id)
            .order_by(Asset.created_at.desc())
            .limit(3)
            .all()
        )
    for a in recent_assets:
        activities.append({
            "icon":  "📦",
            "title": f"Asset: {a.name} — {a.status}",
            "time":  time_ago(a.created_at),
            "raw":   a.created_at
        })

    # Maintenance — admin/manager see all, employee sees only reported by them
    if is_admin_or_manager:
        recent_maint = (
            db.query(MaintenanceRequest)
            .order_by(MaintenanceRequest.created_at.desc())
            .limit(3).all()
        )
    else:
        recent_maint = (
            db.query(MaintenanceRequest)
            .filter(MaintenanceRequest.reported_by_id == current_user.id)
            .order_by(MaintenanceRequest.created_at.desc())
            .limit(3).all()
        )
    for m in recent_maint:
        activities.append({
            "icon":  "🛠️",
            "title": f"Maintenance {m.status}: {m.maintenance_id or 'request'}",
            "time":  time_ago(m.created_at),
            "raw":   m.created_at
        })

    # Reports — only reports generated by this user
    recent_reports = (
        db.query(Report)
        .filter(Report.generated_by_id == current_user.id)
        .order_by(Report.created_at.desc())
        .limit(2).all()
    )
    for r in recent_reports:
        activities.append({
            "icon":  "📊",
            "title": f"Report generated: {r.title}",
            "time":  time_ago(r.created_at),
            "raw":   r.created_at
        })

    # User's own account activity
    activities.append({
        "icon":  "👤",
        "title": f"Account created: {current_user.first_name} {current_user.last_name}",
        "time":  time_ago(current_user.created_at),
        "raw":   current_user.created_at
    })

    # Last login info
    if current_user.joining_date:
        from datetime import datetime as dt
        joined_dt = datetime.combine(current_user.joining_date, datetime.min.time()).replace(tzinfo=timezone.utc)
        activities.append({
            "icon":  "🏢",
            "title": f"Joined organization",
            "time":  time_ago(joined_dt),
            "raw":   joined_dt
        })

    # Last login
    if current_user.last_login:
        activities.append({
            "icon":  "🔐",
            "title": "You logged in",
            "time":  time_ago(current_user.last_login),
            "raw":   current_user.last_login
        })

    # Sort by most recent and return top 8
    activities.sort(
        key=lambda x: (
            x["raw"].replace(tzinfo=timezone.utc)
            if x["raw"] and x["raw"].tzinfo is None
            else x["raw"] or datetime.min.replace(tzinfo=timezone.utc)
        ),
        reverse=True
    )

    return [{"icon": a["icon"], "title": a["title"], "time": a["time"]} for a in activities[:8]]


@router.delete("/{report_id}", status_code=204)
def delete_report(
    report_id: int,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    report = db.query(Report).filter(Report.id == report_id).first()
    if not report:
        raise HTTPException(status_code=404, detail="Report not found.")
    db.delete(report)
    db.commit()